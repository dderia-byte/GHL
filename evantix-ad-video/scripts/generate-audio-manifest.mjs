#!/usr/bin/env node
/**
 * Reads the real duration of every generated voiceover MP3 and writes
 * src/generated/audio-manifest.ts, which src/config/audio-timeline.ts uses
 * to synchronise each scene's length to its narration.
 *
 * Files that haven't been generated yet (e.g. OpenAI access wasn't available
 * when this ran) get a word-count-based estimated duration instead, clearly
 * flagged with source: "estimated" — the manifest is still fully usable for
 * timing the film today, and will automatically switch to exact measured
 * durations the next time this script runs after real files exist.
 */
import { parseFile } from "music-metadata";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const VOICEOVER_DIR = path.join(ROOT, "public", "assets", "voiceover");
const SCRIPT_JSON = path.join(ROOT, "src", "content", "voiceover-script.json");
const OUT_FILE = path.join(ROOT, "src", "generated", "audio-manifest.ts");

// Words-per-second for a calm-but-natural, confident TTS delivery (~156 wpm),
// plus a small fixed allowance for the sentence-final pause TTS engines add.
const WORDS_PER_SECOND = 2.6;
const ESTIMATE_FIXED_PAD_SECONDS = 0.35;

function estimateSeconds(text) {
  const words = text.trim().split(/\s+/).filter(Boolean).length;
  return Number((words / WORDS_PER_SECOND + ESTIMATE_FIXED_PAD_SECONDS).toFixed(2));
}

async function main() {
  if (!existsSync(SCRIPT_JSON)) {
    console.error(`Narration script not found at ${SCRIPT_JSON}`);
    process.exit(1);
  }
  const { segments } = JSON.parse(readFileSync(SCRIPT_JSON, "utf8"));

  const entries = {};
  let measuredCount = 0;
  let estimatedCount = 0;

  for (const segment of segments) {
    const filePath = path.join(VOICEOVER_DIR, segment.fileName);
    const relativeFile = `assets/voiceover/${segment.fileName}`;

    if (existsSync(filePath)) {
      try {
        const metadata = await parseFile(filePath);
        const durationSeconds = Number((metadata.format.duration ?? 0).toFixed(2));
        if (durationSeconds > 0) {
          entries[segment.scene] = { file: relativeFile, durationSeconds, source: "measured" };
          measuredCount++;
          console.log(`Scene ${String(segment.scene).padStart(2, "0")}: measured ${durationSeconds}s from ${segment.fileName}`);
          continue;
        }
        console.warn(`Scene ${String(segment.scene).padStart(2, "0")}: metadata read but duration was 0 — falling back to estimate.`);
      } catch (error) {
        console.warn(`Scene ${String(segment.scene).padStart(2, "0")}: could not read metadata (${error.message}) — falling back to estimate.`);
      }
    }

    const durationSeconds = estimateSeconds(segment.text);
    entries[segment.scene] = { file: relativeFile, durationSeconds, source: "estimated" };
    estimatedCount++;
    console.log(`Scene ${String(segment.scene).padStart(2, "0")}: estimated ${durationSeconds}s (voiceover file not found yet)`);
  }

  mkdirSync(path.dirname(OUT_FILE), { recursive: true });

  const banner = estimatedCount > 0
    ? ` * ${estimatedCount} of ${segments.length} durations are ESTIMATED (word-count based) because the matching\n * voiceover MP3 hasn't been generated yet. Run "npm run generate:voiceover" then\n * "npm run generate:audio-manifest" again to replace estimates with measured durations.`
    : ` * All ${segments.length} durations were measured from the real generated MP3 files.`;

  const contents = `/**
 * AUTO-GENERATED by scripts/generate-audio-manifest.mjs — do not edit by hand.
 * Regenerate with: npm run generate:audio-manifest
 *
${banner}
 */

export interface AudioManifestEntry {
  file: string;
  durationSeconds: number;
  source: "measured" | "estimated";
}

export const generatedAudioManifest: Record<number, AudioManifestEntry> = ${JSON.stringify(entries, null, 2)};
`;

  writeFileSync(OUT_FILE, contents);

  // Plain-JSON sidecar so non-TypeScript Node scripts (music/SFX generation)
  // can read the same manifest without a TS toolchain.
  const jsonOut = OUT_FILE.replace(/\.ts$/, ".json");
  writeFileSync(jsonOut, JSON.stringify(entries, null, 2));

  console.log(`\nWrote ${OUT_FILE}`);
  console.log(`Wrote ${jsonOut}`);
  console.log(`Measured: ${measuredCount}, estimated: ${estimatedCount}.`);
}

main();
